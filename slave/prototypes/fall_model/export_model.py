# Generates ../fall_model_weights.h and ../../test/test_fall_pipeline/golden.h from
# fall_model_weights.b64 + model_meta.json (printed by train_fall_model.py) and raw SisFall.
# Usage: python3 export_model.py <path>/SisFall_dataset
import base64, json, os, sys, zlib
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ACC, GYR, WIN = 2 * 16 / 2**13, 2 * 2000 / 2**16, 100
meta = json.load(open(os.path.join(HERE, "model_meta.json")))
flat = np.frombuffer(zlib.decompress(base64.b64decode(open(os.path.join(HERE, "fall_model_weights.b64")).read())), np.float32)
P, off = {}, 0
for name, shape in meta["shapes"].items():
    n = int(np.prod(shape)); P[name] = flat[off:off + n].reshape(shape); off += n
assert off == flat.size, (off, flat.size)

def load50(root, name):
    subj = name.split("_")[1]
    txt = open(os.path.join(root, subj, name + ".txt")).read().replace(";", ",").replace("\n", "")
    v = np.array([int(x) for x in txt.split(",") if x.strip()], np.float32)
    v = v[: v.size // 9 * 9].reshape(-1, 9)
    x = np.hstack([v[:, 0:3] * ACC, v[:, 3:6] * GYR]); n = x.shape[0] // 4 * 4
    return x[:n].reshape(-1, 4, 6).mean(1).astype(np.float32)

def model_input(w):
    a = w[:, :3].astype(np.float64); g0 = a[:25].mean(0); u = g0 / np.linalg.norm(g0)
    amag = np.linalg.norm(a, axis=1); av = a @ u; ah = np.sqrt(np.maximum(amag**2 - av**2, 0))
    s = meta["acc_scale"]
    return np.stack([amag * s, av * s, ah * s, np.linalg.norm(w[:, 3:], axis=1) * meta["gyr_scale"]]).astype(np.float32)

def forward(x):
    def conv(x, w, b):
        k = w.shape[2]; t = x.shape[1] - k + 1
        y = np.stack([b[o] + sum((w[o, c, j] * x[c, j:j + t] for c in range(w.shape[1]) for j in range(k)))
                      for o in range(w.shape[0])])
        return np.maximum(y, 0)
    pool = lambda x: np.maximum(x[:, 0:x.shape[1] // 2 * 2:2], x[:, 1:x.shape[1] // 2 * 2:2])
    h = pool(conv(x, P["f.0.weight"], P["f.0.bias"])); h = pool(conv(h, P["f.3.weight"], P["f.3.bias"]))
    h = conv(h, P["f.6.weight"], P["f.6.bias"])
    return float(1 / (1 + np.exp(-(P["out.bias"][0] + P["out.weight"][0] @ h.mean(1)))))

def flt(v):
    s = f"{float(v):.9g}"
    return (s if any(c in s for c in ".en") else s + ".0") + "f"

arr = lambda name, a: f"constexpr float {name}[{a.size}] = {{\n    " + ",\n    ".join(
    ", ".join(flt(v) for v in a.ravel()[i:i + 8]) for i in range(0, a.size, 8)) + "};\n"

root = sys.argv[1]
windows = []
for g in meta["gold"]:
    w = load50(root, g["name"])[g["end"] - WIN:g["end"]]
    p = forward(model_input(w))
    print(f'{g["name"]}: prob {p:.6f} (colab {g["prob"]:.6f})')
    assert abs(p - g["prob"]) < 1e-4, "weights or preprocessing do not match the trained model"
    windows.append(w)

hdr = ["#pragma once", "", "// Generated by prototypes/fall_model/export_model.py - do not edit.",
       "// Trained by prototypes/fall_model/train_fall_model.py on SisFall.", "", "namespace fall {", "namespace model {", "",
       f'constexpr float kThreshold = {flt(meta["threshold"])};',
       f'constexpr float kAccScale = {flt(meta["acc_scale"])};', f'constexpr float kGyrScale = {flt(meta["gyr_scale"])};', ""]
for cname, key in [("kConv1W", "f.0.weight"), ("kConv1B", "f.0.bias"), ("kConv2W", "f.3.weight"), ("kConv2B", "f.3.bias"),
                   ("kConv3W", "f.6.weight"), ("kConv3B", "f.6.bias"), ("kDenseW", "out.weight"), ("kDenseB", "out.bias")]:
    hdr.append(arr(cname, P[key]))
hdr += ["}  // namespace model", "}  // namespace fall", ""]
open(os.path.join(HERE, "..", "fall_model_weights.h"), "w").write("\n".join(hdr))

gold = ["#pragma once", "", "// Generated by prototypes/fall_model/export_model.py - do not edit.",
        "// SisFall candidate windows (test subjects) with the values the trained model and the",
        "// Python heuristic gave on them. Frames: ax, ay, az [g], gx, gy, gz [dps] at 50 Hz.", "",
        '#include "../../prototypes/fall_pipeline.h"', "", "struct GoldenWindow {", "    const char* name;",
        "    float peakG;", "    float tiltDeg;", "    bool passesHeuristic;", "    float probability;",
        "    fall::ImuFrame frames[fall::kWindowFrames];", "};", "", "const GoldenWindow kGolden[] = {"]
for g, w in zip(meta["gold"], windows):
    frames = ",\n".join("        {" + ", ".join(flt(v) for v in row) + "}" for row in w)
    gold.append(f'    {{"{g["name"]}", {flt(g["peak"])}, {flt(g["tilt"])}, {str(g["passes"]).lower()}, {flt(g["prob"])},\n     {{\n{frames}}}}},')
gold += ["};", ""]
dst = os.path.join(HERE, "..", "..", "test", "test_fall_pipeline"); os.makedirs(dst, exist_ok=True)
open(os.path.join(dst, "golden.h"), "w").write("\n".join(gold))
print("wrote fall_model_weights.h and test/test_fall_pipeline/golden.h")
